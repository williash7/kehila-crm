// ═══════════════════════════════════════════════════════════════════════════
// זיהוי כפילויות לפני ייבוא.
//
// הרקע: ייבוא חוזר של אותו קובץ יצר כפילויות בשקט, כי המזהה נגזר מחותמת
// זמן שהיא חדשה בכל ייבוא. התיקון בשרת (מזהה מקור + חתימה קנונית) הוא
// ההגנה; מה שנבדק כאן הוא **שכבת ההסבר** — שהמשתמש יראה מה עומד לקרות
// לפני שהוא שומר, ולא יגלה אחרי.
// ═══════════════════════════════════════════════════════════════════════════

const fs = require('fs');
const path = require('path');
const assert = require('assert');
const D = require('/tmp/stub/dupes.js');

let failed = 0;
function ok(c, m) { console.log((c ? '  ✓ ' : '  ✗ ') + m); if (!c) failed = 1; }

// ── נרמול התאריך — הלב של העניין ──
//
// בגיליון יושבים שני פורמטים זה לצד זה: מיילים מנדרים פלוס מגיעים עם
// לוכסנים, ומה שהאפליקציה כותבת מגיע עם נקודות. השוואה על המחרוזת
// הגולמית הייתה מפספסת בדיוק את מה שהיא מחפשת.
console.log('א. תאריך — שני הפורמטים שבגיליון מתלכדים:');
ok(D.normDate('17/08/2026') === '2026-08-17', 'לוכסנים');
ok(D.normDate('17.08.2026') === '2026-08-17', 'נקודות');
ok(D.normDate('2026-08-17') === '2026-08-17', 'ISO');
ok(D.normDate('7/8/2026')   === '2026-08-07', 'ספרה בודדת מרופדת');
ok(D.normDate('17/08/2026') === D.normDate('17.08.2026'), 'לוכסנים ונקודות = אותו יום');
ok(D.normDate('') === '' && D.normDate(null) === '', 'ריק נשאר ריק');
ok(D.normDate('לא תאריך') === 'לא תאריך', 'מה שאינו תאריך אינו מומצא');

console.log('\nב. סכום — אגורות שלמות:');
ok(D.normAmount('₪1,200.00') === 120000, 'מטבע ופסיקים');
ok(D.normAmount(1200) === D.normAmount('1200.00'), 'מספר וטקסט זהים');
ok(D.normAmount('500') === D.normAmount(' 500 '), 'רווחים');
ok(D.normAmount('שלוש מאות') === 0, 'טקסט שאינו מספר');

console.log('\nג. שם — מה שלא הופך אדם לאדם אחר:');
ok(D.normName('  ישראל   ישראלי ') === 'ישראל ישראלי', 'רווחים כפולים');
ok(D.normName('ישראל ישראלי') === D.normName('ישראל‏ ישראלי'), 'סימן כיווניות');
ok(D.normName("יעקב 'גורביץ'") === D.normName('יעקב גורביץ'), 'גרשיים');

// ── הזיהוי עצמו ──
const existing = [
  { id: 'ned:A100', name: 'ישראל ישראלי', date: '17/08/2026', amount: 500 },
  { id: 'man:99',   name: 'שרה כהן',      date: '16.08.2026', amount: 300 },
];

console.log('\nד. זיהוי מול היומן:');
{
  const r = D.findDuplicates([
    { name: 'ישראל ישראלי', date: '17.08.2026', amount: 500 },   // אותו יום, פורמט אחר
    { name: 'שרה כהן',      date: '16/08/2026', amount: '₪300' }, // גם סכום בפורמט אחר
    { name: 'דוד לוי',      date: '18/08/2026', amount: 700 },   // חדש
  ], existing);
  ok(r.existing.length === 2, 'שתי השורות הקיימות זוהו למרות פורמט שונה');
  ok(r.fresh.length === 1 && r.fresh[0].name === 'דוד לוי', 'החדשה עברה');
}

console.log('\nה. מזהה מקור גובר, גם עם קידומת אחרת:');
{
  const r = D.findDuplicates(
    [{ id: 'A100', name: 'שם אחר לגמרי', date: '01/01/2020', amount: 9 }], existing);
  ok(r.existing.length === 1, 'מספר האישור זוהה למרות שכל השאר שונה');
}

console.log('\nו. תרומה כפולה אמיתית באותו יום — נשמרת:');
{
  // תורם שנתן פעמיים ₪100 באותו יום. חתימה יציבה לבדה הייתה ממזגת אותן
  // ומוחקת כסף אמיתי — זו המלכודת שבגללה יש סיומת סידורית בשרת.
  const r = D.findDuplicates([
    { name: 'אבי מזרחי', date: '20/08/2026', amount: 100 },
    { name: 'אבי מזרחי', date: '20/08/2026', amount: 100 },
  ], []);
  ok(r.fresh.length === 2, 'שתיהן עוברות — לא נמחק כסף');
  ok(r.existing.length === 0, 'ואף אחת אינה "קיימת ביומן"');
  ok(r.repeatedInFile.length === 1, 'אבל המשתמש מקבל התרעה שהן חוזרות');
}

console.log('\nז. קלט פגום אינו מפיל:');
ok(D.findDuplicates([], []).fresh.length === 0, 'רשימה ריקה');
ok(D.findDuplicates(null, null).fresh.length === 0, 'null');
ok(D.findDuplicates([null, undefined], []).fresh.length === 0, 'שורות ריקות');

// ── והחיבור למסך ──
console.log('\nח. הצד של האפליקציה:');
{
  const root = path.join(__dirname, '..');
  const modal = fs.readFileSync(root + '/src/components/GlobalAIImportModal.tsx', 'utf8');

  ok(/id: '12345'/.test(modal), 'הסכמה מבקשת מזהה לתרומות');
  ok(/id: '1866314'/.test(modal), 'והסכמה מבקשת מזהה להוראות קבע');
  ok(/אל תמציא מזהה/.test(modal),
     'ההוראה לא להמציא — מזהה מומצא גרוע מחסר, כי הוא נראה יציב ואינו');
  ok(/findDuplicates/.test(modal), 'המסך משתמש בזיהוי');
  ok(/removeExistingDonations/.test(modal), 'ואפשר להסיר את הקיימות בלחיצה');
  ok(/rejected/.test(modal), 'הדחיות מהשרת מוצגות');
  ok(/דילוג אינו שגיאה/.test(modal), 'ומוסבר שדילוג אינו תקלה');
}

console.log('\n✓ זיהוי כפילויות בייבוא');
process.exitCode = failed;
