import { useEffect } from 'react';

// ─────────────────────────────────────────────────────────────────────────────
// „קח אותי לפריט הזה” — החוזה בין החיפוש למסכי היעד.
//
// ── הבעיה ─────────────────────────────────────────────────────────────────
//
// מנוע החיפוש אוסף `entityId` לכל תוצאה, אבל החיבור הראשון זרק אותו והחליף
// לשונית בלבד. מי שחיפש „מאור” וקיבל תרומה של ₪500, הגיע ללשונית התרומות
// **בלי סינון ובלי סימון** — וצריך היה לחפש אותה שוב ידנית.
//
// כלומר הפעולה שהחיפוש בא לחסוך — „לחפש בתוך המסך” — נשארה בדיוק כפי
// שהייתה.
//
// ── הצורה ─────────────────────────────────────────────────────────────────
//
// `count` קיים מאותה סיבה שהוא קיים ב-`addTrigger`: בלעדיו, לחיצה על **אותה
// תוצאה** פעמיים לא הייתה עושה כלום, כי ה-prop לא היה משתנה. הוא חותמת זמן,
// לא מונה.
//
// זהו prop צר שעובר לרכיב היעד — **לא מצב גלובלי חדש.** מצב גלובלי נוסף היה
// אומר שכל מסך צריך לדעת על קיומו של החיפוש, וזה בדיוק הכיוון ההפוך.
//
// ── שתי דרכים להגיע לפריט ─────────────────────────────────────────────────
//
// יש מסכים עם „חוזה פתיחה” קיים — תרומות פותחות חלון פרטים, קמפיין נפתח לפי
// `openId`. שם פותחים ישירות, וזו התוצאה הטובה ביותר.
//
// לפעילויות ולמשימות אין מושג כזה: הן נפרשות ברשימה ואין „פתח פריט”.
// שם מגוללים ומדגישים. פחות טוב מפתיחה, והרבה יותר טוב מלנחות על מסך
// ולחפש מחדש.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * מה שרכיב היעד מקבל.
 *
 * `onConsumed` הוא החלק שנשכח בגרסה הראשונה, והוא נחוץ: בלעדיו היעד נשאר
 * תלוי ב-App, וכל הרכבה מחדש של הרכיב — מעבר למסך אחר וחזרה — הייתה
 * **פותחת שוב את הפריט הישן**. המשתמש היה חוזר לרשימת התרומות שעה אחר כך
 * ומקבל חלון שנפתח לבד.
 */
export interface OpenTargetProps {
  openTarget?: OpenTarget | null;
  onOpenTargetConsumed?: () => void;
}

export interface OpenTarget {
  /** מזהה הפריט המבוקש. */
  id: string;
  /** ההקשר שאליו הפריט שייך — חג או פעילות עבור משימה. */
  parentId?: string;
  /** חותמת זמן, כדי שאותה בקשה פעמיים תפעל פעמיים. */
  count: number;
}

/** התכונה שרכיב מסמן בה את עצמו כיעד אפשרי. */
export const ENTITY_ATTR = 'data-entity-id';

/** מחלקת ההדגשה הזמנית. מוגדרת ב-index.css. */
export const HIGHLIGHT_CLASS = 'entity-highlight';

/** כמה זמן ההדגשה נשארת. מספיק כדי לתפוס את העין, לא מספיק כדי להציק. */
const HIGHLIGHT_MS = 2600;

/**
 * מגוללת אל הפריט ומדגישה אותו.
 *
 * הריצה נדחית ב-`requestAnimationFrame` כפול: הרכיב היעד עשוי עדיין לא
 * להיות ב-DOM ברגע שהלשונית התחלפה, ובלי ההמתנה החיפוש היה „לא עושה כלום”
 * בדיוק בפעם הראשונה — כשהמסך נטען מחדש.
 */
export function revealEntity(id: string): boolean {
  const el = document.querySelector<HTMLElement>(`[${ENTITY_ATTR}="${CSS.escape(id)}"]`);
  if (!el) return false;

  el.scrollIntoView({ behavior: 'smooth', block: 'center' });
  el.classList.add(HIGHLIGHT_CLASS);
  window.setTimeout(() => el.classList.remove(HIGHLIGHT_CLASS), HIGHLIGHT_MS);
  return true;
}

/**
 * מנסה להגיע לפריט, עם כמה ניסיונות.
 *
 * רשימות ארוכות מצוירות בהדרגה, ולכן הפריט עשוי להופיע רק אחרי כמה פריימים.
 * מנסים כמה פעמים ואז מוותרים בשקט — **הוויתור השקט מכוון**: אם הפריט אינו
 * ברשימה (נמחק, סונן), עדיף שהמשתמש יראה את המסך מאשר הודעת שגיאה על משהו
 * שהוא לא ביקש.
 */
export function useRevealEntity(
  target: OpenTarget | null | undefined,
  enabled = true,
  onConsumed?: () => void
): void {
  useEffect(() => {
    if (!enabled || !target?.id) return;

    let tries = 0;
    let frame = 0;
    let timer = 0;
    let done = false;

    // נצרך גם בהצלחה **וגם בוויתור**.
    //
    // אילו היינו צורכים רק בהצלחה, יעד שלא נמצא היה נשאר תלוי לנצח — וכל
    // כניסה עתידית למסך הייתה מנסה שוב לגלול לפריט שכבר לא קיים.
    const finish = () => { if (!done) { done = true; onConsumed?.(); } };

    const attempt = () => {
      if (revealEntity(target.id)) { finish(); return; }
      if (++tries > 12) { finish(); return; }   // ~1.2 שניות, ואז מוותרים
      timer = window.setTimeout(() => { frame = requestAnimationFrame(attempt); }, 100);
    };

    frame = requestAnimationFrame(attempt);
    return () => { cancelAnimationFrame(frame); clearTimeout(timer); };
  }, [target?.id, target?.count, enabled]);
}
